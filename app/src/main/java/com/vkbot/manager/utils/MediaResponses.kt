    /**
     * Возвращает случайный ответ для заданного типа вложения.
     * Если тип не найден, возвращает null.
     */
    fun getRandomResponse(type: String): String? {
        val list = responses[type]
        return if (!list.isNullOrEmpty()) {
            list.random()
        } else {
            null
        }
    }
